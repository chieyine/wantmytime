	<p class="eyebrow">Acceptable use</p>
	<h1 class="page-heading">Use your link responsibly.</h1>
	<p>WantMyTime is for selling your time and attention: advice, mentoring, consultations, conversations. These rules apply to everyone who uses it, sellers and buyers alike.</p>
	<h2>Not allowed</h2>
	<ul>
		<li>Anything illegal where you or the other person are, or anything that helps someone break the law.</li>
		<li>Sexual services, adult content, or anything involving anyone under 18.</li>
		<li>Gambling, betting tips sold as guaranteed wins, investment schemes promising returns, pyramid or “double your money” schemes, and unlicensed financial, legal or medical services where a licence is required.</li>
		<li>Pretending to be someone else, using someone else’s name or photo, or misleading people about who you are or what you offer.</li>
		<li>Harassment, threats, hate, or recording a call without the other person’s consent where the law requires it.</li>
		<li>Using WantMyTime to move money that isn’t payment for time actually offered, including paying yourself with stolen cards or accounts.</li>
		<li>Asking people to pay you outside WantMyTime for a booking made through it.</li>
		<li>Interfering with the service: scraping, probing for weaknesses, overloading it, or getting around its limits.</li>
	</ul>
	<h2>Professional services</h2>
	<p>If you give professional advice (medical, legal, financial or similar), you must hold any licence or registration your country requires and follow your profession’s rules. A WantMyTime booking does not by itself create a professional relationship beyond what you and the buyer agree.</p>
	<h2>What happens if the rules are broken</h2>
	<p>We can pause a link, cancel bookings and refund buyers, hold payouts connected to suspected fraud while we investigate, or close an account. Report a concern to <a class="text-link" href="mailto:support@wantmytime.com">support@wantmytime.com</a>.</p>
